import type { Account, Connection, ConnectionStatus } from "./types";

interface AccountRow {
  readonly id: number;
  readonly institution_origin: string;
  readonly canvas_user_id: string;
  readonly created_at: number;
}

function toAccount(row: AccountRow): Account {
  return {
    id: row.id,
    institutionOrigin: row.institution_origin,
    canvasUserId: row.canvas_user_id,
    createdAt: row.created_at,
  };
}

interface ConnectionRow {
  readonly id: string;
  readonly account_id: number;
  readonly status: ConnectionStatus;
  readonly generation: number;
  readonly key_version: number;
  readonly encrypted_access_token: string;
  readonly encrypted_refresh_token: string | null;
  readonly access_token_expires_at: number | null;
  readonly created_at: number;
  readonly revoked_at: number | null;
}

function toConnection(row: ConnectionRow): Connection {
  return {
    id: row.id,
    accountId: row.account_id,
    status: row.status,
    generation: row.generation,
    keyVersion: row.key_version,
    encryptedAccessToken: row.encrypted_access_token,
    encryptedRefreshToken: row.encrypted_refresh_token,
    accessTokenExpiresAt: row.access_token_expires_at,
    createdAt: row.created_at,
    revokedAt: row.revoked_at,
  };
}

const CONNECTION_COLUMNS =
  "id, account_id, status, generation, key_version, encrypted_access_token, encrypted_refresh_token, access_token_expires_at, created_at, revoked_at";

/**
 * Finds the account for this institution + Canvas user id, creating it on first sighting.
 * The composite key means the same Canvas user id at a different institution is always a
 * distinct account, never a collision. Never takes a caller-supplied account id — identity is
 * derived only from the institution/Canvas-user-id pair a caller has already verified.
 */
export async function findOrCreateAccount(
  db: D1Database,
  institutionOrigin: string,
  canvasUserId: string,
  now: number,
): Promise<Account> {
  const inserted = await db
    .prepare(
      `INSERT INTO accounts (institution_origin, canvas_user_id, created_at)
       VALUES (?1, ?2, ?3)
       ON CONFLICT (institution_origin, canvas_user_id) DO NOTHING
       RETURNING id, institution_origin, canvas_user_id, created_at`,
    )
    .bind(institutionOrigin, canvasUserId, now)
    .first<AccountRow>();
  if (inserted) return toAccount(inserted);

  const existing = await db
    .prepare(
      `SELECT id, institution_origin, canvas_user_id, created_at
       FROM accounts
       WHERE institution_origin = ?1 AND canvas_user_id = ?2`,
    )
    .bind(institutionOrigin, canvasUserId)
    .first<AccountRow>();
  if (!existing) throw new Error("account lookup failed after insert conflict");
  return toAccount(existing);
}

export interface CreateConnectionInput {
  /** Generated by the caller (e.g. `crypto.randomUUID()`) before the credential is encrypted, so
   * the connection id is available for the encryption envelope's associated data ahead of insert. */
  readonly id: string;
  readonly accountId: number;
  readonly keyVersion: number;
  readonly encryptedAccessToken: string;
  readonly encryptedRefreshToken: string | null;
  readonly accessTokenExpiresAt: number | null;
  readonly now: number;
}

export async function createConnection(db: D1Database, input: CreateConnectionInput): Promise<Connection> {
  const row = await db
    .prepare(
      `INSERT INTO connections
         (id, account_id, status, generation, key_version, encrypted_access_token, encrypted_refresh_token, access_token_expires_at, created_at)
       VALUES (?1, ?2, 'active', 1, ?3, ?4, ?5, ?6, ?7)
       RETURNING ${CONNECTION_COLUMNS}`,
    )
    .bind(
      input.id,
      input.accountId,
      input.keyVersion,
      input.encryptedAccessToken,
      input.encryptedRefreshToken,
      input.accessTokenExpiresAt,
      input.now,
    )
    .first<ConnectionRow>();
  if (!row) throw new Error("connection insert returned no row");
  return toConnection(row);
}

/** Returns the connection only while it's active; a revoked or deleted connection reads as
 * absent, which is what callers checking the fence (see below) want. */
export async function getActiveConnection(db: D1Database, connectionId: string): Promise<Connection | undefined> {
  const row = await db
    .prepare(`SELECT ${CONNECTION_COLUMNS} FROM connections WHERE id = ?1 AND status = 'active'`)
    .bind(connectionId)
    .first<ConnectionRow>();
  return row ? toConnection(row) : undefined;
}

/** Throws unless the connection is still active at exactly the generation the caller captured
 * earlier — rejecting both a revoked/removed connection and a stale generation (revoked, then
 * reconnected) in one check, without a caller needing to compare fields itself. */
export async function assertConnectionFence(
  db: D1Database,
  connectionId: string,
  expectedGeneration: number,
): Promise<void> {
  const connection = await getActiveConnection(db, connectionId);
  if (!connection) throw new Error("connection is not active");
  if (connection.generation !== expectedGeneration) throw new Error("connection generation is stale");
}

/**
 * Marks an active connection revoked and bumps its fencing generation. Requires the connection
 * to currently be active — revoking an already-revoked or missing connection throws — so
 * `revokedAt`/the generation bump only ever happen once per revoke, matching the
 * "revoke with the provider, then delete" order the credential lifecycle depends on.
 */
export async function revokeConnection(db: D1Database, connectionId: string, now: number): Promise<Connection> {
  const row = await db
    .prepare(
      `UPDATE connections
       SET status = 'revoked', generation = generation + 1, revoked_at = ?2
       WHERE id = ?1 AND status = 'active'
       RETURNING ${CONNECTION_COLUMNS}`,
    )
    .bind(connectionId, now)
    .first<ConnectionRow>();
  if (!row) throw new Error("connection not found or already revoked");
  return toConnection(row);
}

/** Deletes a connection's row, permanently discarding its encrypted credential. Only a revoked
 * connection can be deleted — a caller can never skip straight from active to gone, which is the
 * ordering `revocation-order.test.ts` locks in. */
export async function deleteConnection(db: D1Database, connectionId: string): Promise<void> {
  const result = await db.prepare(`DELETE FROM connections WHERE id = ?1 AND status = 'revoked'`).bind(connectionId).run();
  if (result.meta.changes === 0) throw new Error("connection not found or not yet revoked");
}

/** Every connection an account owns, active or revoked. Route handlers project this down to a
 * credential-free summary before returning it to a caller — this function itself still returns
 * the full row (including the encrypted envelope) because it's also the right shape for internal
 * callers that need it, e.g. re-encrypting on refresh. */
export async function getConnectionsForAccount(db: D1Database, accountId: number): Promise<Connection[]> {
  const result = await db
    .prepare(`SELECT ${CONNECTION_COLUMNS} FROM connections WHERE account_id = ?1 ORDER BY created_at ASC`)
    .bind(accountId)
    .all<ConnectionRow>();
  return result.results.map(toConnection);
}

export interface RefreshedCredentials {
  readonly keyVersion: number;
  readonly encryptedAccessToken: string;
  readonly encryptedRefreshToken: string | null;
  readonly accessTokenExpiresAt: number | null;
}

/** Persists a re-encrypted credential after a token refresh. Folds the connection fence into the
 * same atomic statement as the write (`status = 'active' AND generation = ?`), so a connection
 * revoked between the caller's fence check and this write can never have its envelope silently
 * resurrected — the same TOCTOU concern `revokeConnection`'s single-statement update guards
 * against. */
export async function updateConnectionCredentials(
  db: D1Database,
  connectionId: string,
  expectedGeneration: number,
  credentials: RefreshedCredentials,
): Promise<Connection> {
  const row = await db
    .prepare(
      `UPDATE connections
       SET key_version = ?3, encrypted_access_token = ?4, encrypted_refresh_token = ?5, access_token_expires_at = ?6
       WHERE id = ?1 AND status = 'active' AND generation = ?2
       RETURNING ${CONNECTION_COLUMNS}`,
    )
    .bind(
      connectionId,
      expectedGeneration,
      credentials.keyVersion,
      credentials.encryptedAccessToken,
      credentials.encryptedRefreshToken,
      credentials.accessTokenExpiresAt,
    )
    .first<ConnectionRow>();
  if (!row) throw new Error("connection is not active");
  return toConnection(row);
}

/** True when no connection row (active or revoked-but-not-yet-deleted) still references this key
 * version — i.e. it's safe to drop the key from the ring's legacy map. A revoked connection still
 * counts until its row is actually deleted, since its stored envelope is still encrypted under
 * that version until then. */
export async function isKeyVersionRetirable(db: D1Database, keyVersion: number): Promise<boolean> {
  const row = await db.prepare(`SELECT 1 FROM connections WHERE key_version = ?1 LIMIT 1`).bind(keyVersion).first();
  return row === null;
}
