//! Readable, owner-marked Markdown exports for imported Canvas coursework.

#[path = "canvas_item_export_io.rs"]
mod io;
#[path = "canvas_item_export_markdown.rs"]
mod markdown;

use std::collections::{BTreeMap, BTreeSet};
use std::fs::{self, OpenOptions};
use std::io::Read;
#[cfg(unix)]
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Component, Path, PathBuf};

use serde_json::Value;

const CONFIG_FILE: &str = "class-folders.json";
const MAX_CONFIG_BYTES: u64 = 1024 * 1024;
const MAX_CONFIG_COURSES: usize = 500;
const MAX_EXPORT_BYTES: usize = 4 * 1024 * 1024;
const MARKER: &str =
    "<!-- Generated by Due Good from Canvas; this file is replaced on every refresh. -->";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ExportStatus {
    Complete,
    Disabled,
    Failed,
}

impl ExportStatus {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::Complete => "complete",
            Self::Disabled => "disabled",
            Self::Failed => "failed",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ExportSummary {
    pub(crate) status: ExportStatus,
    pub(crate) written: usize,
    pub(crate) unchanged: usize,
    pub(crate) skipped_owner_files: usize,
}

impl ExportSummary {
    fn disabled() -> Self {
        Self {
            status: ExportStatus::Disabled,
            written: 0,
            unchanged: 0,
            skipped_owner_files: 0,
        }
    }
}

struct CourseFolder {
    path: PathBuf,
    canonical: PathBuf,
}

/// Exports assignments and discussions to configured class folders.
///
/// Filesystem and configuration problems are summarized without paths or coursework content.
pub(crate) fn export_coursework(data_root: &Path, coursework: &Value) -> ExportSummary {
    let folders = match read_class_folders(data_root) {
        Some(folders) => folders,
        None => return ExportSummary::disabled(),
    };
    let courses = match coursework.get("courses").and_then(Value::as_array) {
        Some(courses) => courses,
        None => return failed_summary(),
    };
    let items = match coursework.get("items").and_then(Value::as_array) {
        Some(items) => items,
        None => return failed_summary(),
    };
    let course_names = courses
        .iter()
        .filter_map(|course| {
            let key = course.get("key")?.as_str()?;
            let canvas_id = positive_id(Some(course.get("canvasCourseId")?))?;
            Some((key.to_owned(), (canvas_id, course_label(course))))
        })
        .collect::<BTreeMap<_, _>>();

    let mut summary = ExportSummary {
        status: ExportStatus::Complete,
        written: 0,
        unchanged: 0,
        skipped_owner_files: 0,
    };
    let mut targets = BTreeSet::new();
    for item in items {
        if !is_exportable_canvas_item(item) {
            continue;
        }
        let Some(course_key) = item.get("course").and_then(Value::as_str) else {
            continue;
        };
        let Some((canvas_course_id, course_label)) = course_names.get(course_key) else {
            continue;
        };
        let Some(folder) = folders.get(canvas_course_id) else {
            continue;
        };
        let Some(canvas_item_id) =
            positive_id(item.get("canvasId").or_else(|| item.get("canvas_id")))
        else {
            summary.status = ExportStatus::Failed;
            continue;
        };
        let title = item
            .get("title")
            .and_then(Value::as_str)
            .unwrap_or("Canvas item");
        let mut slug = slug(title);
        let mut target = folder.path.join("assignments").join(&slug).join("source");
        if !targets.insert(target.clone()) {
            slug = unique_slug(&slug, canvas_item_id);
            target = folder.path.join("assignments").join(&slug).join("source");
            if !targets.insert(target.clone()) {
                summary.status = ExportStatus::Failed;
                continue;
            }
        }
        let markdown =
            match markdown::render_readme(item, *canvas_course_id, canvas_item_id, course_label) {
                Some(markdown) if markdown.len() <= MAX_EXPORT_BYTES => markdown,
                _ => {
                    summary.status = ExportStatus::Failed;
                    continue;
                }
            };
        let relative_directory = Path::new("assignments").join(&slug).join("source");
        let outcome = io::write_item_file(folder, &relative_directory, &markdown);
        match outcome {
            io::ItemWrite::Written => summary.written += 1,
            io::ItemWrite::Unchanged => summary.unchanged += 1,
            io::ItemWrite::OwnerFile => summary.skipped_owner_files += 1,
            io::ItemWrite::Failed => summary.status = ExportStatus::Failed,
        }
    }
    summary
}

fn is_exportable_canvas_item(item: &Value) -> bool {
    let canvas_id = positive_id(item.get("canvasId").or_else(|| item.get("canvas_id")));
    if canvas_id.is_none() {
        return false;
    }
    let canvas_reference = item
        .get("sourceReferences")
        .and_then(Value::as_array)
        .is_some_and(|references| {
            let id = canvas_id.expect("checked above").to_string();
            references.iter().any(|reference| {
                reference.get("source").and_then(Value::as_str) == Some("canvas")
                    && reference.get("id").and_then(Value::as_str) == Some(id.as_str())
            })
        });
    if item.get("source").and_then(Value::as_str) != Some("canvas") && !canvas_reference {
        return false;
    }
    let kind = item
        .get("canvasResourceType")
        .and_then(Value::as_str)
        .or_else(|| item.get("canvas_resource_type").and_then(Value::as_str));
    if let Some(kind) = kind {
        return kind == "assignment" || kind == "discussion";
    }
    item.get("kind").and_then(Value::as_str) != Some("class")
}

fn failed_summary() -> ExportSummary {
    ExportSummary {
        status: ExportStatus::Failed,
        written: 0,
        unchanged: 0,
        skipped_owner_files: 0,
    }
}

fn read_class_folders(data_root: &Path) -> Option<BTreeMap<u64, CourseFolder>> {
    let path = data_root.join(CONFIG_FILE);
    let bytes = read_config_no_follow(&path)?;
    let value: Value = serde_json::from_slice(&bytes).ok()?;
    let object = value.as_object()?;
    if object.len() != 2 || object.get("schemaVersion")?.as_u64()? != 1 {
        return None;
    }
    let configured = object.get("courses")?.as_object()?;
    if configured.len() > MAX_CONFIG_COURSES {
        return None;
    }
    let mut result = BTreeMap::new();
    for (course_id, configured_path) in configured {
        let id = parse_positive_id(course_id)?;
        let path = PathBuf::from(configured_path.as_str()?);
        if !path.is_absolute()
            || path
                .components()
                .any(|part| matches!(part, Component::ParentDir))
        {
            return None;
        }
        let configured_metadata = directory_metadata_without_symlinks(&path)?;
        let canonical = fs::canonicalize(&path).ok()?;
        let canonical_metadata = directory_metadata_without_symlinks(&canonical)?;
        if !same_node(&configured_metadata, &canonical_metadata) {
            return None;
        }
        if result
            .insert(
                id,
                CourseFolder {
                    path: canonical.clone(),
                    canonical,
                },
            )
            .is_some()
        {
            return None;
        }
    }
    Some(result)
}

fn directory_metadata_without_symlinks(path: &Path) -> Option<fs::Metadata> {
    let mut current = PathBuf::new();
    for component in path.components() {
        match component {
            Component::RootDir | Component::Prefix(_) => current.push(component.as_os_str()),
            Component::Normal(name) => current.push(name),
            Component::CurDir | Component::ParentDir => return None,
        }
        let metadata = fs::symlink_metadata(&current).ok()?;
        if metadata.file_type().is_symlink() {
            return None;
        }
        if current != path && !metadata.is_dir() {
            return None;
        }
    }
    let metadata = fs::symlink_metadata(path).ok()?;
    metadata.is_dir().then_some(metadata)
}

#[cfg(unix)]
fn read_config_no_follow(path: &Path) -> Option<Vec<u8>> {
    let before = fs::symlink_metadata(path).ok()?;
    if !before.is_file() || before.file_type().is_symlink() || before.len() > MAX_CONFIG_BYTES {
        return None;
    }
    let file = OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path)
        .ok()?;
    let opened = file.metadata().ok()?;
    let after = fs::symlink_metadata(path).ok()?;
    if !opened.is_file() || !same_node(&before, &opened) || !same_node(&before, &after) {
        return None;
    }
    let mut bytes = Vec::with_capacity(opened.len() as usize);
    file.take(MAX_CONFIG_BYTES + 1)
        .read_to_end(&mut bytes)
        .ok()?;
    (bytes.len() as u64 <= MAX_CONFIG_BYTES).then_some(bytes)
}

#[cfg(not(unix))]
fn read_config_no_follow(path: &Path) -> Option<Vec<u8>> {
    let metadata = fs::symlink_metadata(path).ok()?;
    if !metadata.is_file() || metadata.file_type().is_symlink() || metadata.len() > MAX_CONFIG_BYTES
    {
        return None;
    }
    fs::read(path).ok()
}

#[cfg(unix)]
fn same_node(left: &fs::Metadata, right: &fs::Metadata) -> bool {
    use std::os::unix::fs::MetadataExt;
    left.dev() == right.dev() && left.ino() == right.ino() && left.file_type() == right.file_type()
}

#[cfg(not(unix))]
fn same_node(left: &fs::Metadata, right: &fs::Metadata) -> bool {
    left.file_type() == right.file_type() && left.len() == right.len()
}

fn parse_positive_id(value: &str) -> Option<u64> {
    if value.is_empty()
        || value.starts_with('0')
        || !value.bytes().all(|byte| byte.is_ascii_digit())
    {
        return None;
    }
    value.parse::<u64>().ok().filter(|id| *id > 0)
}

fn positive_id(value: Option<&Value>) -> Option<u64> {
    let value = value?;
    value
        .as_u64()
        .or_else(|| value.as_str().and_then(|value| parse_positive_id(value)))
        .filter(|id| *id > 0)
}

fn course_label(course: &Value) -> String {
    let code = course
        .get("code")
        .and_then(Value::as_str)
        .unwrap_or("")
        .trim();
    let title = course
        .get("title")
        .and_then(Value::as_str)
        .or_else(|| course.get("name").and_then(Value::as_str))
        .unwrap_or("Canvas course")
        .trim();
    if code.is_empty() {
        title.to_owned()
    } else {
        format!("{code} — {title}")
    }
}

fn slug(title: &str) -> String {
    let mut output = String::new();
    let mut separator = false;
    for character in title.chars() {
        if character.is_ascii_alphanumeric() {
            if separator && !output.is_empty() && output.len() < 60 {
                output.push('-');
            }
            if output.len() < 60 {
                output.push(character.to_ascii_lowercase());
            }
            separator = false;
        } else {
            separator = true;
        }
    }
    let output = output.trim_matches('-').to_owned();
    if output.is_empty() {
        "canvas-item".into()
    } else {
        output
    }
}

fn unique_slug(slug: &str, item_id: u64) -> String {
    let suffix = format!("-{item_id}");
    let prefix_len = 60usize.saturating_sub(suffix.len());
    format!(
        "{}{suffix}",
        slug.chars()
            .take(prefix_len)
            .collect::<String>()
            .trim_end_matches('-')
    )
}

